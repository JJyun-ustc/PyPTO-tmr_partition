"""Export frozen residual weights and fixed seq_len=3500 calibration to C++."""

import argparse
import json
import re
from pathlib import Path

import numpy as np
import torch
from round2_shadow import literal
from round2_train import Attention


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("models", type=Path)
    ap.add_argument("header", type=Path)
    ap.add_argument("--update-test-fixture", action="store_true")
    args = ap.parse_args()
    w = json.loads((args.models / "weights.json").read_text())
    cal = json.loads((args.models / "calibration.json").read_text())
    root = Path(__file__).resolve().parents[4]
    license_text = (
        (root / "src/a2a3/runtime/tensormap_and_ringbuffer/runtime/qkv_batch.h").read_text().split("#pragma once", 1)[0]
    )
    # A generated header is a frozen experiment artifact, never an online trainer.
    s = license_text + (
        "// Generated by round2_export.py from frozen actual-action training data.\n"
        "#pragma once\n"
        "#include <cmath>\n"
        "namespace simpler::tmr::learned {\n"
    )
    for name, value in [(k, w[k]) for k in ("mean", "std", "residual_mean", "residual_std", "linear")] + [
        (k.replace(".", "_"), v) for k, v in w["attention"].items()
    ]:
        shape = "".join(f"[{n}]" for n in np.array(value).shape)
        s += f"inline constexpr double {name}{shape}={literal(value)};\n"
    s += (
        "struct Calibration {\n"
        "  int kernel[3], blocks, mask, sync;\n"
        "  double runtime_us;\n"
        "};\n"
        "inline constexpr Calibration calibration[] = {\n"
    )
    for key, row in cal["table"].items():
        k0, k1, k2, b, m, sync = map(int, key.split(","))
        runtime = max(0.02, row["intercept_us"] + 3500 * row["per_seq_us"])
        s += "{{" + f"{k0},{k1},{k2}" + "}," + f"{b},{m},{sync},{runtime:.17g}" + "},\n"
    s += (
        "}\n"
        ";\n"
        "inline double runtime(const int *kernels, int blocks, int mask, int sync) {\n"
        "  for (const auto &r : calibration)\n"
        "    if (r.kernel[0] == kernels[0] && r.kernel[1] == kernels[1] &&\n"
        "        r.kernel[2] == kernels[2] && r.blocks == blocks && r.mask == mask &&\n"
        "        r.sync == sync)\n"
        "      return r.runtime_us;\n"
        "  return -1;\n"
        "}\n"
    )
    s += (
        "\n"
        "inline void residual(const double x[12], const double tokens[3][5], double y[2])"
        " {\n"
        "  double q[4]{}, k[3][4]{}, v[3][4]{}, logits[3]{}, z[4]{};\n"
        "  for (int d = 0; d < 4; ++d) {\n"
        "    q[d] = q_bias[d];\n"
        "    for (int j = 0; j < 12; ++j)\n"
        "      q[d] += q_weight[d][j] * x[j];\n"
        "    for (int a = 0; a < 3; ++a) {\n"
        "      k[a][d] = k_bias[d];\n"
        "      v[a][d] = v_bias[d];\n"
        "      for (int j = 0; j < 5; ++j) {\n"
        "        k[a][d] += k_weight[d][j] * tokens[a][j];\n"
        "        v[a][d] += v_weight[d][j] * tokens[a][j];\n"
        "      }\n"
        "      logits[a] += q[d] * k[a][d] / 2;\n"
        "    }\n"
        "  }\n"
        "  double top = logits[0];\n"
        "  for (int a = 1; a < 3; ++a)\n"
        "    if (logits[a] > top)\n"
        "      top = logits[a];\n"
        "  double sum = 0;\n"
        "  for (int a = 0; a < 3; ++a) {\n"
        "    logits[a] = std::exp(logits[a] - top);\n"
        "    sum += logits[a];\n"
        "  }\n"
        "  for (int a = 0; a < 3; ++a)\n"
        "    for (int d = 0; d < 4; ++d)\n"
        "      z[d] += logits[a] / sum * v[a][d];\n"
        "  for (int o = 0; o < 2; ++o) {\n"
        "    y[o] = skip_bias[o] + out_bias[o];\n"
        "    for (int j = 0; j < 12; ++j)\n"
        "      y[o] += skip_weight[o][j] * x[j];\n"
        "    for (int d = 0; d < 4; ++d)\n"
        "      y[o] += out_weight[o][d] * z[d];\n"
        "    y[o] = y[o] * residual_std[o] + residual_mean[o];\n"
        "  }\n"
        "}\n"
        "} // namespace simpler::tmr::learned\n"
    )
    args.header.write_text(s)
    if args.update_test_fixture:
        row = cal["table"]["-1,4,-1,1,2,0"]
        run = max(0.02, row["intercept_us"] + 3500 * row["per_seq_us"])
        wait = 1.7 * run
        raw = np.array(
            [
                1 / 30,
                1,
                0.2,
                0.5,
                0.9,
                0.1,
                30 / 32,
                2 / 7,
                4 / 36,
                0.5,
                wait / 100,
                run / 100,
            ]
        )
        x = (raw - w["mean"]) / w["std"]
        tokens = np.array(
            [
                [
                    [1, 0, 1, 0, 30 / 32],
                    [0.5, 0.5, 0, 1, 30 / 32],
                    [0.9, 1, 0, 0, 30 / 32],
                ]
            ]
        )
        model = Attention()
        model.load_state_dict(torch.load(args.models / "attention.pt", weights_only=True))
        model.eval()
        with torch.no_grad():
            res = model(
                torch.tensor(x[None], dtype=torch.float32),
                torch.tensor(tokens, dtype=torch.float32),
            ).numpy()[0]
        result = np.maximum(np.array([wait, run]) + res * w["residual_std"] + w["residual_mean"], 0).sum()
        test = root / "tests/ut/cpp/a2a3/runtime/tensormap_and_ringbuffer/test_scheduler_state.cpp"
        body, count = re.subn(
            r"expected_pytorch_score = [0-9eE.+-]+;",
            f"expected_pytorch_score = {result:.17g};",
            test.read_text(),
        )
        assert count == 1
        test.write_text(body)


if __name__ == "__main__":
    main()
